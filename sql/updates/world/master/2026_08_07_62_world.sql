--
-- Weighted Enemy Forces (retail model): per-creature point weights per challenge dungeon.
-- A dungeon with rows here uses weighted crediting: each kill adds its creature's points and
-- unlisted creatures (boss adds etc.) credit nothing. requiredKills in challenge_mode_enemy_forces
-- holds the required POINT total for such dungeons.
--
CREATE TABLE IF NOT EXISTS `challenge_mode_enemy_forces_creature` (
  `challengeModeId` INT UNSIGNED NOT NULL COMMENT 'MapChallengeMode.db2 ID',
  `creatureEntry` INT UNSIGNED NOT NULL,
  `points` INT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Forces points credited per kill',
  PRIMARY KEY (`challengeModeId`, `creatureEntry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Mythic+ weighted enemy forces (CriteriaTree-derived)';

